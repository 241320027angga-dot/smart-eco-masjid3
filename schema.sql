-- Smart Eco-Masjid / Eco-Jamaah
-- Jalankan di Supabase SQL Editor.

create table if not exists public.sensor_readings (
  id bigint generated by default as identity primary key,
  device_id text not null,
  tds numeric(10,2) not null check (tds >= 0 and tds <= 5000),
  ph numeric(5,2) not null check (ph >= 0 and ph <= 14),
  flow_rate numeric(10,2) not null check (flow_rate >= 0 and flow_rate <= 100),
  pump_status text not null check (pump_status in ('ON','OFF')),
  esp32_status text not null check (esp32_status in ('online','offline')),
  recorded_at timestamptz not null default now()
);

create index if not exists sensor_readings_recorded_at_idx
  on public.sensor_readings (recorded_at desc);

create index if not exists sensor_readings_device_time_idx
  on public.sensor_readings (device_id, recorded_at desc);

-- Server menggunakan SUPABASE_SERVICE_ROLE_KEY, sehingga RLS tidak wajib
-- untuk endpoint server-to-Supabase. Tetap aktifkan RLS sebagai pertahanan
-- tambahan jika tabel kelak diakses langsung dari browser.

alter table public.sensor_readings enable row level security;

-- Tidak memberi akses INSERT/UPDATE/DELETE ke anon/authenticated.
-- Endpoint Node/Express adalah satu-satunya jalur tulis untuk ESP32.
revoke all on table public.sensor_readings from anon, authenticated;
